export function isRtl(lang) { return RTL.has(lang); }
export function dirFor(lang) { return isRtl(lang) ? 'rtl' : 'ltr'; }

/** Picks a supported language from a stored choice or navigator.languages; falls back to he. */
export function resolveLang(stored, preferred = []) {
  if (LANGS.includes(stored)) return stored;
  for (const p of preferred) {
    const base = String(p).toLowerCase().split('-')[0];
    if (base === 'iw') return 'he';
    if (LANGS.includes(base)) return base;
  }
  return DEFAULT_LANG;
}

/** Lookup with fallback: lang -> en -> key itself (a missing key is visible, never silent). */
export function t(lang, key, params = {}) {
  const s = (STRINGS[lang] && STRINGS[lang][key]) ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m));
}

/** Applies lang + dir to a document root (or any element). */
export function applyLang(el, lang) {
  el.setAttribute('lang', lang);
  el.setAttribute('dir', dirFor(lang));
}
